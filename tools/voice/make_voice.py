"""Record every couplet once with an open Tamil voice, for the app's built-in Listen.

Voice: Piper "ta_IN-rasa_female-medium" (huggingface.co/tinisoft/piper-ta_IN-rasa_female-medium), trained on the
female speaker of AI4Bharat's Rasa dataset. CC BY 4.0, credited in the app's Sources page.

Needs Python with `pip install piper-tts imageio-ffmpeg`, and the model's .onnx and .onnx.json in one folder.
Run from the project root:

    python tools/voice/make_voice.py <model folder>

Writes assets/voice/NNNN.webm (Opus, mono) and src/lib/voiceFiles.ts (generated; never edit it). Couplets come only
from assets/kural/pack.json. Already-recorded couplets are kept unless --all is given.
"""
import json
import subprocess
import sys
import tempfile
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PACK = ROOT / "assets/kural/pack.json"
OUT = ROOT / "assets/voice"
INDEX = ROOT / "src/lib/voiceFiles.ts"

# A little slower than the model's natural pace, as a couplet is recited, with a pause between its two lines.
LENGTH_SCALE = 1.3
LINE_PAUSE_S = 0.55
BITRATE = "24k"


def main():
    from imageio_ffmpeg import get_ffmpeg_exe
    from piper import PiperVoice, SynthesisConfig

    model_dir = Path(sys.argv[1])
    redo = "--all" in sys.argv
    voice = PiperVoice.load(str(next(model_dir.glob("*.onnx"))))
    cfg = SynthesisConfig(length_scale=LENGTH_SCALE)
    ffmpeg = get_ffmpeg_exe()
    kurals = json.loads(PACK.read_text(encoding="utf-8"))["kurals"]
    OUT.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory() as tmp:
        for k in kurals:
            dest = OUT / f"{k['n']:04d}.webm"
            if dest.exists() and not redo:
                continue
            parts = []
            for i, line in enumerate((k["a"], k["b"])):
                p = Path(tmp) / f"{i}.wav"
                with wave.open(str(p), "wb") as w:
                    voice.synthesize_wav(line, w, syn_config=cfg)
                parts.append(p)
            rate = voice.config.sample_rate
            # Line one, a pause, line two; then a gentle loudness level and Opus for speech.
            cmd = [ffmpeg, "-y", "-loglevel", "error", "-i", str(parts[0]), "-i", str(parts[1]), "-filter_complex",
                   f"aevalsrc=0:d={LINE_PAUSE_S}:s={rate}[gap];[0:a][gap][1:a]concat=n=3:v=0:a=1,"
                   "loudnorm=I=-18:TP=-2:LRA=11[out]",
                   "-map", "[out]", "-ac", "1", "-c:a", "libopus", "-b:a", BITRATE, "-application", "voip", str(dest)]
            subprocess.run(cmd, check=True)
            if k["n"] % 50 == 0:
                print(k["n"], flush=True)

    lines = ["// Generated by tools/voice/make_voice.py. Never edit by hand.", "",
             "// Each couplet recorded once with the open Piper Tamil voice (CC BY 4.0).",
             "export const VOICE_FILES: Record<number, number> = {"]
    for k in kurals:
        lines.append(f"  {k['n']}: require('../../assets/voice/{k['n']:04d}.webm'),")
    lines.append("};")
    INDEX.write_text("\n".join(lines) + "\n", encoding="utf-8")
    total = sum(f.stat().st_size for f in OUT.glob("*.webm"))
    print(f"{len(kurals)} couplets, {total // 1024} KB -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
